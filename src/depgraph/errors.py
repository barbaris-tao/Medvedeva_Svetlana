"""Типы исключений, используемые инструментом."""


class DepGraphError(Exception):
    """Базовый класс для всех ожидаемых ошибок времени выполнения."""


class ConfigError(DepGraphError):
    """Возникает, когда пользовательский параметр недопустим."""


class RepositoryError(DepGraphError):
    """Возникает, когда данные пакета невозможно прочитать из репозитория."""


class RenderError(DepGraphError):
    """Возникает, когда изображение графа невозможно создать."""